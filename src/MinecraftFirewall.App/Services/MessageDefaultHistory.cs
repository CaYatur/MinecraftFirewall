    /// <summary>True when this text is one an earlier release shipped, which means nobody has edited
    /// it and replacing it takes nothing away.</summary>
    public static bool IsAnUneditedDefault(string key, string value) =>
        PreviousDefaults.TryGetValue(key, out string[]? values) &&
        Array.IndexOf(values, value) >= 0;

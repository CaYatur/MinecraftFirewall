namespace MinecraftFirewall.App.Services;

/// <summary>
/// Every value each player-facing message has shipped with in an earlier release.
///
/// This exists to answer one question safely: has somebody edited this message, or is it simply old?
/// Configuration wins over the compiled defaults — which is right, it is their file — but it means a
/// default that improves in a new release never reaches anybody who installed an older one. Their
/// prompts stay as they were, and there is nothing to tell them why.
///
/// A message whose current value is one this project shipped is a message nobody has touched, and
/// bringing it up to date takes nothing from them. A message that matches none of them was written by
/// a person, and is never touched.
///
/// Generated by tools/generate-message-history.py, which reads every v1.* tag rather than trusting
/// anybody to maintain a list. A list kept by hand would rot the first time somebody forgot to add to
/// it, and it would fail in the worst direction: silently replacing something somebody wrote.
/// </summary>
